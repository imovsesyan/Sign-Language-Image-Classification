import os

IMAGE_EXTS = (".jpg", ".jpeg", ".png", ".bmp", ".gif", ".webp")

def is_image_folder(folder):
    if not os.path.isdir(folder):
        return False
    # folder must contain subfolders (classes)
    subdirs = [d for d in os.listdir(folder) if os.path.isdir(os.path.join(folder, d))]
    if len(subdirs) < 2:
        return False
    # at least one subdir must contain images
    for sd in subdirs:
        sd_path = os.path.join(folder, sd)
        files = os.listdir(sd_path)
        if any(f.lower().endswith(IMAGE_EXTS) for f in files):
            return True
    return False

def find_data_dir(root):
    # check root first
    if is_image_folder(root):
        return root
    # search deeper
    for dirpath, dirnames, filenames in os.walk(root):
        if is_image_folder(dirpath):
            return dirpath
    return None

